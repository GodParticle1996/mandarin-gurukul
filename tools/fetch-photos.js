const sleep = ms => new Promise(r => setTimeout(r, ms));
/* Wikimedia tez requests par 429 deta hai → ruko aur dobara (10s, 20s, 40s) */
async function get(url) {
  for (let k = 0; k < 4; k++) {
    const r = await fetch(url, { headers: UA });
    if (r.status !== 429) return r;
    await sleep(10000 * 2 ** k);
  }
  throw new Error('429 — baad mein dobara chalao');
}
const api = async (host, params) => {
  const u = `https://${host}/w/api.php?` + new URLSearchParams({ format: 'json', formatversion: '2', ...params });
  const r = await get(u);
  if (!r.ok) throw new Error(`${host} ${r.status}`);
  return r.json();
};
const strip = s => String(s || '').replace(/<[^>]+>/g, '').replace(/\s+/g, ' ').trim();

async function one([key, title, words], credits) {
  const out = path.join(IMG, key + '.jpg');
  const p = await api('en.wikipedia.org', { action: 'query', titles: title, prop: 'pageimages', piprop: 'thumbnail|name', pithumbsize: '480', redirects: '1' });
  const page = p.query && p.query.pages && p.query.pages[0];
  if (!page || !page.thumbnail || !page.pageimage) throw new Error('lead photo nahi mili');
  const file = page.pageimage;
  const m = await api('commons.wikimedia.org', { action: 'query', titles: 'File:' + file, prop: 'imageinfo', iiprop: 'extmetadata|url' });
  const info = m.query && m.query.pages && m.query.pages[0] && m.query.pages[0].imageinfo && m.query.pages[0].imageinfo[0];
  const meta = (info && info.extmetadata) || {};
  const license = strip(meta.LicenseShortName && meta.LicenseShortName.value) || 'see source';
  if (/fair use|non-free/i.test(license)) throw new Error('license free nahi: ' + license);
  const img = await get(page.thumbnail.source);
  if (!img.ok) throw new Error('download ' + img.status);
  fs.writeFileSync(out, Buffer.from(await img.arrayBuffer()));
  credits[key] = {
    src: `img/${key}.jpg`, words: words.split('|'), title: page.title,
    author: strip(meta.Artist && meta.Artist.value).slice(0, 120) || 'unknown',
    license, page: info ? info.descriptionurl : `https://commons.wikimedia.org/wiki/File:${encodeURIComponent(file)}`,
  };
  return `${key}: ${file} (${license})`;
}

(async () => {
  fs.mkdirSync(IMG, { recursive: true });
  const prevFile = path.join(ROOT, 'photos.js');
  let credits = {};
  if (fs.existsSync(prevFile)) {
    const m = /MG\.PHOTOS = (\{[\s\S]*\});/.exec(fs.readFileSync(prevFile, 'utf8'));
    if (m) credits = JSON.parse(m[1]);
  }
  const only = process.argv[2];
  for (const row of LIST) {
    if (only ? row[0] !== only : (credits[row[0]] && fs.existsSync(path.join(IMG, row[0] + '.jpg')))) continue;
    try { console.log('✅', await one(row, credits)); }
    catch (e) { console.log('❌', row[0], e.message); delete credits[row[0]]; }
    await sleep(2000);
  }
  const header = '/* AUTO-GENERATED by tools/fetch-photos.js — Wikimedia photos + credits.\n'
    + '   Phrase ke zh mein `words` mein se koi shabd ho → card par yeh photo. */\n';
  fs.writeFileSync(prevFile, header + 'MG.PHOTOS = ' + JSON.stringify(credits, null, 1) + ';\n');
  console.log(`\n${Object.keys(credits).length} photos → photos.js`);
})();
